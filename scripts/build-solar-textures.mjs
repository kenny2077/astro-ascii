// Pack locally downloaded, credited Solar System Scope maps for offline file:// use.
// Usage: node scripts/build-solar-textures.mjs /path/to/downloaded/maps
import {readFileSync,writeFileSync} from 'node:fs';
import {resolve,join,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
const source=process.argv[2];
if(!source)throw new Error('Provide the directory containing the maps listed in art/solar-system/TEXTURES.md');
const names={sun:'sun',mercury:'mercury',venus:'venus_atmosphere',earth:'earth_daymap',earth_clouds:'earth_clouds',mars:'mars',jupiter:'jupiter',saturn:'saturn',saturn_ring:'saturn_ring_alpha',uranus:'uranus',neptune:'neptune'};
const data={};
for(const [id,name] of Object.entries(names)){const ext=id==='saturn_ring'?'png':'jpg';data[id]=`data:image/${ext==='jpg'?'jpeg':'png'};base64,${readFileSync(join(source,`${name}.${ext}`)).toString('base64')}`;}
writeFileSync(resolve(dirname(fileURLToPath(import.meta.url)),'../art/solar-system/textures.js'),'// Solar System Scope / INOVE, CC BY 4.0. See TEXTURES.md. Generated by scripts/build-solar-textures.mjs.\nconst SOLAR_TEXTURES = '+JSON.stringify(data)+';\n');
